// Helper to resolve category metadata from slug or query
export const getCategoryBySlug = (slug?: string): Category | undefined => {
  if (!slug) return undefined;
  const normalized = slug.toLowerCase().trim();
  return (
    CURATED_CATEGORIES.find((c) => c.slug === normalized || c.id === normalized) ||
    CURATED_CATEGORIES.find((c) => c.name.toLowerCase().includes(normalized))
  );
};

